'use strict';
const assert = require('node:assert/strict');
const { installTestStore, responseRecorder } = require('./managed-profile-test-store.cjs');
const store = installTestStore();
const core = require('../server-src/_lib/doctorai-core.cjs');
const profiles = require('../server-src/health/profiles.js');
const health = require('../server-src/health/state.js');
const documents = require('../api/documents.js');
async function call(handler, session, method = 'POST', body = {}) {
  const response = responseRecorder();
  await handler({ method, headers: { cookie: `doctorai_session=${core.signedToken(session)}` }, query: {}, body }, response);
  return response;
}
(async () => {
  const productionLike = core.createSession({ sub: 'synthetic-a', email: 'account-a@example.invalid' });
  await core.activateSession(productionLike);
  await core.saveEntitlement(productionLike, { tier: 'pro', exp: core.nowSeconds() + 3600 });
  process.env.VERCEL_ENV = 'preview';
  for (const key of ['AUTH_SECRET', 'KV_REST_API_URL', 'KV_REST_API_TOKEN', 'BLOB_READ_WRITE_TOKEN']) delete process.env[`PREVIEW_${key}`];
  let count = store.calls.length;
  assert.equal(core.configured(), false);
  assert.equal(core.storageConfigured(), false);
  assert.equal(core.documentStorageConfigured(), false);
  for (const handler of [profiles, health, documents]) assert.equal((await call(handler, productionLike)).statusCode, 401);
  assert.equal(store.calls.length, count, 'Unconfigured Preview cannot even read an inherited production session store.');
  for (const key of ['AUTH_SECRET', 'KV_REST_API_URL', 'KV_REST_API_TOKEN', 'BLOB_READ_WRITE_TOKEN']) process.env[`PREVIEW_${key}`] = process.env[key];
  assert.equal(core.configured(), false);
  assert.equal(core.storageConfigured(), false);
  assert.equal(core.documentStorageConfigured(), false);
  process.env.AUTH_SECRET = 'synthetic-shared-secret';
  process.env.KV_REST_API_URL = 'https://shared-store.invalid';
  process.env.KV_REST_API_TOKEN = 'synthetic-shared-token';
  process.env.BLOB_READ_WRITE_TOKEN = 'synthetic-shared-blob';
  process.env.PREVIEW_AUTH_SECRET = 'synthetic-isolated-secret';
  process.env.PREVIEW_KV_REST_API_URL = 'https://synthetic-store.invalid';
  process.env.PREVIEW_KV_REST_API_TOKEN = 'synthetic-isolated-token';
  process.env.PREVIEW_BLOB_READ_WRITE_TOKEN = 'synthetic-isolated-blob';
  assert.equal(core.storageConfigured(), true);
  assert.equal(core.documentStorageConfigured(), true);
  for (const key of ['AUTH_SECRET', 'KV_REST_API_URL', 'KV_REST_API_TOKEN']) {
    const isolated = process.env[`PREVIEW_${key}`];
    process.env[`PREVIEW_${key}`] = process.env[key];
    assert.equal(core.storageConfigured(), false, `Reject shared ${key}.`);
    process.env[`PREVIEW_${key}`] = isolated;
  }
  const endpoint = process.env.PREVIEW_KV_REST_API_URL;
  process.env.PREVIEW_KV_REST_API_URL = 'https://SHARED-store.invalid/different-path/';
  assert.equal(core.storageConfigured(), false, 'Changing URL spelling/path cannot bypass the shared-origin guard.');
  process.env.PREVIEW_KV_REST_API_URL = endpoint;
  const session = core.createSession({ sub: 'preview-a', email: 'preview-a@example.invalid' });
  await core.activateSession(session);
  await core.saveEntitlement(session, { tier: 'pro', exp: core.nowSeconds() + 3600 });
  assert.equal((await call(health, session, 'PUT', { state: { profile: { name: 'Synthetic isolated account' } } })).statusCode, 200);
  assert.equal((await call(health, session, 'GET')).body.state.profile.name, 'Synthetic isolated account');
  const document = await call(documents, session, 'POST', { name: 'synthetic-isolated.txt', data: 'data:text/plain;base64,c3ludGhldGlj' });
  assert.equal(document.statusCode, 201);
  assert.equal(store.blobCalls[0].token, 'synthetic-isolated-blob', 'Blob SDK must receive the isolated token explicitly.');
  process.env.PREVIEW_BLOB_READ_WRITE_TOKEN = process.env.BLOB_READ_WRITE_TOKEN;
  const blobCount = store.blobCalls.length;
  assert.equal(core.documentStorageConfigured(), false);
  assert.equal((await call(documents, session)).statusCode, 503);
  assert.equal(store.blobCalls.length, blobCount, 'Shared Blob token cannot be used for private operations.');
  delete process.env.PREVIEW_KV_REST_API_TOKEN;
  count = store.calls.length;
  for (const handler of [profiles, health, documents]) assert.equal((await call(handler, session)).statusCode, 401);
  assert.equal(await core.activeEntitlement({}, session), null);
  assert.equal(store.calls.length, count);
  console.log('Preview isolation verification passed: absent/shared configuration makes zero storage calls; dedicated synthetic Auth/KV/Blob works; shared Blob and missing KV fail closed. No deployed authentication or live storage.');
})().catch(error => { console.error(error); process.exitCode = 1; });
