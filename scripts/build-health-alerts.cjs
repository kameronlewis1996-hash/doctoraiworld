'use strict';

// Generate the browser's local-only alert engine from the existing authoritative
// medicine engine and public terminology data. Never hand-edit medical copies.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const engineSource = read('server-src/medication/safety-engine.cjs');
const alertsSource = read('server-src/health/alerts-engine.cjs');
const seed = JSON.parse(read('data/medication/medication-safety.seed.json'));
const nz = JSON.parse(read('data/medication/nz-pharmac-medicines.json'));
// Preserve every field accessed by safety-engine.cjs. Omit unused funding detail
// to keep the browser payload smaller; the labels and ingredient sets are intact.
const browserCatalogue = { ...nz, products: nz.products.map(product => {
  const item = {};
  for (const key of ['name', 'brand', 'chemical', 'formulation', 'ingredients', 'ingredientsComplete']) if (Object.hasOwn(product, key)) item[key] = product[key];
  if (product.schedules) item.schedules = true;
  return item;
}) };
const moduleBody = `'use strict';\nconst medicationModule={exports:{}};\n(function(module,require){\n${engineSource}\n})(medicationModule,function(id){if(id==='../../data/medication/medication-safety.seed.json')return ${JSON.stringify(seed)};if(id==='../../data/medication/nz-pharmac-medicines.json')return ${JSON.stringify(browserCatalogue)};throw new Error('Unexpected local module: '+id);});\nconst alertsModule={exports:{}};\n(function(module){\n${alertsSource}\n})(alertsModule);\nreturn alertsModule.exports.createHealthAlertsEngine(medicationModule.exports);`;
const signature = crypto.createHash('sha256').update(engineSource).update(alertsSource).update(JSON.stringify(seed)).update(JSON.stringify(browserCatalogue)).digest('hex');
const output = `// GENERATED by scripts/build-health-alerts.cjs. Public sourced rules only; no health records.\n// Source SHA-256: ${signature}\n(function(root,factory){if(typeof module==='object'&&module.exports){module.exports=factory();}else{root.DoctorAIHealthAlerts=factory();}})(typeof globalThis!=='undefined'?globalThis:this,function(){\n${moduleBody}\n});\n`;
const outputPath = path.join(root, 'health-alerts.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== output) throw new Error('health-alerts.js is stale; run node scripts/build-health-alerts.cjs');
  console.log('Local alerts browser bundle matches its source engine and public catalogue.');
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated health-alerts.js (${Buffer.byteLength(output)} bytes) from shared local medicine rules.`);
}
